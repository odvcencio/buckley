func stageRepo(t *testing.T, files map[string]string) {
	t.Helper()
	cfg := config.DefaultConfig()
	cfg.Buckbot.GeneratedGlobs = nil
	restore := loadCommitGeneratedConfig
	loadCommitGeneratedConfig = func() (*config.Config, error) { return cfg, nil }
	t.Cleanup(func() {
		loadCommitGeneratedConfig = restore
		diffsignal.SetGeneratedResolver(nil)
	})
	dir := t.TempDir()
	for name, body := range files {
		full := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, args := range [][]string{{"init", "-q"}, {"add", "-A"}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = dir
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}
	t.Chdir(dir)
}

func TestGeneratedCommitRuntime(t *testing.T) {
	attrs := ".gitattributes"
	t.Run("generated only skips the model", func(t *testing.T) {
		stageRepo(t, map[string]string{
			attrs:                 "client/js/*.js linguist-generated\n",
			"client/js/bundle.js": "var zorblax=1;\n",
		})
		// .gitattributes itself is a source file, so stage only the bundle.
		rt := generatedCommitRuntime(commitCommandOptions{paths: []string{"client/js/bundle.js"}}, repoOpState{Kind: opNone})
		if rt == nil {
			t.Fatal("expected a fixed runtime")
		}
		res, err := rt.runner.Run(context.Background())
		if err != nil || res.Commit == nil {
			t.Fatalf("run: %v %v", res, err)
		}
		if got := res.Commit.Header(); got != "update(client): regenerate bundle.js" {
			t.Fatalf("header = %q", got)
		}
	})
	t.Run("mixed commit calls the model", func(t *testing.T) {
		stageRepo(t, map[string]string{
			attrs:                 "client/js/*.js linguist-generated\n",
			"client/js/bundle.js": "var a=1;\n",
			"main.go":             "package main\n",
		})
		if rt := generatedCommitRuntime(commitCommandOptions{}, repoOpState{Kind: opNone}); rt != nil {
			t.Fatal("mixed commit must use the model")
		}
	})
	t.Run("merge in progress calls the model", func(t *testing.T) {
		stageRepo(t, map[string]string{attrs: "*.js linguist-generated\n", "a.js": "x\n"})
		if rt := generatedCommitRuntime(commitCommandOptions{paths: []string{"a.js"}}, repoOpState{Kind: opMerge}); rt != nil {
			t.Fatal("merge commits must not use the template")
		}
	})
}

func gitInCwd(args ...string) (string, error) {
	out, err := exec.Command("git", args...).CombinedOutput()
	return string(out), err
}

// A bundle with its compressed copies and source map is regeneration output
// even when .gitattributes does not say so; the message must say that and name
// the source.
func TestGeneratedCommitRuntime_BundleWithSiblings(t *testing.T) {
	stageRepo(t, map[string]string{
		"client/js/patch.js":     "export const patch = 1;\n",
		"client/js/patch.js.br":  "br\n",
		"client/js/patch.js.gz":  "gz\n",
		"client/js/patch.js.map": `{"version":3,"sources":["../src/patch.ts"],"mappings":"AAAA"}` + "\n",
	})
	rt := generatedCommitRuntime(commitCommandOptions{}, repoOpState{Kind: opNone})
	if rt == nil {
		t.Fatal("a bundle with siblings and a source map must skip the model")
	}
	res, err := rt.runner.Run(context.Background())
	if err != nil || res.Commit == nil {
		t.Fatalf("run: %v %v", res, err)
	}
	if got := res.Commit.Header(); got != "update(client): regenerate patch.js" {
		t.Fatalf("header = %q", got)
	}
	if got := strings.Join(res.Commit.Body, "\n"); !strings.Contains(got, "Regenerate from src/patch.ts") {
		t.Fatalf("body = %q, want it to name src/patch.ts", got)
	}
}

func TestGeneratedCommitRuntime_CodeGeneratedHeaderAndConfiguredGlob(t *testing.T) {
	stageRepo(t, map[string]string{
		"gen/types.go":         "// Code generated by gentypes. DO NOT EDIT.\n\npackage gen\n",
		"fixtures/case-1.html": "<p>1</p>\n",
	})
	if rt := generatedCommitRuntime(commitCommandOptions{}, repoOpState{Kind: opNone}); rt != nil {
		t.Fatal("an unmarked fixture beside generated code is hand-written as far as Buckley can tell")
	}

	cfg := config.DefaultConfig()
	cfg.Buckbot.GeneratedGlobs = []string{"fixtures/**"}
	loadCommitGeneratedConfig = func() (*config.Config, error) { return cfg, nil }
	rt := generatedCommitRuntime(commitCommandOptions{}, repoOpState{Kind: opNone})
	if rt == nil {
		t.Fatal("configured globs and the header should make the whole change generated")
	}
	res, err := rt.runner.Run(context.Background())
	if err != nil || res.Commit == nil {
		t.Fatalf("run: %v %v", res, err)
	}
	if got := res.Commit.Header(); !strings.HasPrefix(got, "update: regenerate") {
		t.Fatalf("header = %q", got)
	}
	if got := strings.Join(res.Commit.Body, "\n"); !strings.Contains(got, "gentypes") {
		t.Fatalf("body = %q, want it to name gentypes", got)
	}
}
