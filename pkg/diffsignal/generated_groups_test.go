func TestSplit_GeneratedByHint(t *testing.T) {
	raw := newFileDiff("gen/types.go", "+// Code generated by protoc-gen-go. DO NOT EDIT.\n+package gen\n") +
		newFileDiff("web/app.js", "+x\n") +
		newFileDiff("web/app.js.map", `+{"version":3,"sources":["../src/app.ts","../src/b.ts"],"mappings":""}`+"\n")
	by := map[string]string{}
	for _, f := range Split(raw) {
		by[f.Path] = f.GeneratedBy
	}
	if by["gen/types.go"] != "protoc-gen-go" {
		t.Errorf("header tool = %q", by["gen/types.go"])
	}
	if by["web/app.js.map"] != "src/app.ts and 1 more sources" {
		t.Errorf("map source = %q", by["web/app.js.map"])
	}
	if by["web/app.js"] != "" {
		t.Errorf("a file with no marker named %q", by["web/app.js"])
	}
}

func TestCapture_ClassifiesSiblingsAndHeaders(t *testing.T) {
	raw := newFileDiff("client/patch.js", "+export const patch = 1;\n") +
		newFileDiff("client/patch.js.br", "+x\n") +
		newFileDiff("gen/types.go", "+// Code generated by gentypes. DO NOT EDIT.\n+package gen\n") +
		newFileDiff("src/app.go", "+package src\n")
	var c Capture
	if _, err := c.Write([]byte(raw)); err != nil {
		t.Fatal(err)
	}
	d, err := c.Finish()
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]FileDiff{}
	for _, f := range d.Files {
		got[f.Path] = f
	}
	if !got["client/patch.js"].Generated() || !got["gen/types.go"].Generated() {
		t.Errorf("capture reasons: patch.js=%q types.go=%q", got["client/patch.js"].Reason, got["gen/types.go"].Reason)
	}
	if got["src/app.go"].Generated() {
		t.Errorf("hand-written file classified %q", got["src/app.go"].Reason)
	}
	if got["gen/types.go"].GeneratedBy != "gentypes" || got["client/patch.js.br"].DiffBytes == 0 {
		t.Errorf("hint=%q bytes=%d", got["gen/types.go"].GeneratedBy, got["client/patch.js.br"].DiffBytes)
	}
}

func TestSplit_CompressedCopiesBesideGeneratedFileAreGenerated(t *testing.T) {
	binary := func(p string) string {
		return fmt.Sprintf("diff --git a/%[1]s b/%[1]s\nindex 5555555..6666666 100644\nBinary files a/%[1]s and b/%[1]s differ\n", p)
	}
	raw := newFileDiff("client/patch.js", "+export const patch = 1;\n") +
		binary("client/patch.js.br") + binary("client/patch.js.gz") +
		newFileDiff("client/patch.js.map", "+{}\n") +
		binary("assets/logo.png") + binary("assets/orphan.js.gz")
	got := map[string]Reason{}
	for _, f := range Split(raw) {
		got[f.Path] = f.Reason
	}
	for _, p := range []string{"client/patch.js", "client/patch.js.br", "client/patch.js.gz", "client/patch.js.map"} {
		if !(FileDiff{Reason: got[p]}).Generated() {
			t.Errorf("%s reason = %q, want generated", p, got[p])
		}
	}
	if got["assets/logo.png"] != ReasonBinary || got["assets/orphan.js.gz"] != ReasonBinary {
		t.Errorf("binaries with no generated neighbour: logo=%q orphan=%q, want binary", got["assets/logo.png"], got["assets/orphan.js.gz"])
	}
}
