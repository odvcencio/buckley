func newFileDiff(path string, body string) string {
	return fmt.Sprintf("diff --git a/%[1]s b/%[1]s\nnew file mode 100644\nindex 0000000..1111111\n--- /dev/null\n+++ b/%[1]s\n@@ -0,0 +1,%[3]d @@\n%[2]s", path, body, strings.Count(body, "\n"))
}

func TestSplit_GeneratedHeader(t *testing.T) {
	raw := newFileDiff("gen/types.go", "+// Code generated by gentypes. DO NOT EDIT.\n+\n+package gen\n") +
		newFileDiff("src/app.go", "+package src\n+\n+// Code generated by hand? DO NOT EDIT is a lie here\n")
	files := Split(raw)
	if files[0].Reason != ReasonGeneratedHeader || !files[0].Generated() {
		t.Fatalf("gen/types.go reason = %q, want generated header", files[0].Reason)
	}
	if files[1].Generated() {
		t.Fatalf("src/app.go reason = %q; a marker below line 1 must not count", files[1].Reason)
	}
}

func TestSplit_GeneratedHeaderNeedsFileTop(t *testing.T) {
	seg := "diff --git a/x.go b/x.go\n--- a/x.go\n+++ b/x.go\n@@ -40,3 +40,3 @@\n // Code generated by x. DO NOT EDIT.\n-old\n+new\n"
	if got := Split(seg)[0]; got.Generated() {
		t.Fatalf("hunk at line 40 classified %q", got.Reason)
	}
}

func TestSplit_GeneratedSiblings(t *testing.T) {
	raw := newFileDiff("client/patch.js", "+export const patch = 1;\n") +
		newFileDiff("client/patch.js.br", "+x\n") +
		newFileDiff("client/other.js", "+export const other = 1;\n") +
		newFileDiff("client/third.js", "+export const third = 1;\n") +
		newFileDiff("client/third.js.map", "+{}\n")
	byPath := map[string]FileDiff{}
	for _, f := range Split(raw) {
		byPath[f.Path] = f
	}
	for _, p := range []string{"client/patch.js", "client/third.js"} {
		if byPath[p].Reason != ReasonGeneratedSibling {
			t.Errorf("%s reason = %q, want build output sibling", p, byPath[p].Reason)
		}
	}
	if byPath["client/other.js"].Generated() {
		t.Errorf("client/other.js has no generated sibling but was classified %q", byPath["client/other.js"].Reason)
	}
}

func TestGroupGenerated(t *testing.T) {
	var raw strings.Builder
	for i := 0; i < 3; i++ {
		raw.WriteString(newFileDiff(fmt.Sprintf("fx/perf/c%d.html", i), "+<p>\n"))
		raw.WriteString(newFileDiff(fmt.Sprintf("fx/perf/c%d.json", i), "+{}\n"))
	}
	raw.WriteString(newFileDiff("src/real.go", "+package src\n"))
	raw.WriteString(newFileDiff("web/app.js", "+x\n"))
	raw.WriteString(newFileDiff("web/app.js.gz", "+x\n"))
	raw.WriteString(newFileDiff("web/app.js.br", "+x\n"))
	SetGeneratedResolver(NewGeneratedResolver("", []string{"fx/perf/**"}))
	defer SetGeneratedResolver(nil)

	groups := GroupGenerated(Split(raw.String()))
	got := map[string]GeneratedGroup{}
	for _, g := range groups {
		got[g.Pattern] = g
	}
	for _, pattern := range []string{"fx/perf/*.html", "fx/perf/*.json", "web/*.js.gz", "web/*.js.br"} {
		g, ok := got[pattern]
		if !ok && pattern != "web/*.js.gz" && pattern != "web/*.js.br" {
			t.Fatalf("missing group %q in %v", pattern, groups)
		}
		_ = g
	}
	if g := got["fx/perf/*.html"]; len(g.Files) != 3 || g.Bytes == 0 {
		t.Fatalf("html group = %+v, want 3 files and nonzero bytes", g)
	}
	if _, ok := got["src/real.go"]; ok {
		t.Fatal("hand-written file grouped")
	}
	if g := got["web/app.js"]; len(g.Files) != 1 || g.Pattern != "web/app.js" {
		t.Fatalf("sibling source group = %+v", g)
	}
	line := got["fx/perf/*.html"].Line()
	if !strings.Contains(line, "fx/perf/*.html | 3 files |") || !strings.Contains(line, "changed") {
		t.Fatalf("line = %q", line)
	}
}

